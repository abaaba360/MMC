def make_p(pstyle, text):
    p = OxmlElement('w:p')
    ppr = OxmlElement('w:pPr')
    if pstyle:
        ps = OxmlElement('w:pStyle'); ps.set(qn('w:val'), pstyle); ppr.append(ps)
    p.append(ppr)
    r = OxmlElement('w:r')
    if body_rpr is not None:
        r.append(copy.deepcopy(body_rpr))
    t = OxmlElement('w:t'); t.set(qn('xml:space'), 'preserve'); t.text = text
    r.append(t)
    p.append(r)
    return p

