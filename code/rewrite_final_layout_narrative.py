def find_paragraph(doc: Document, prefix: str) -> Paragraph:
    hits = [p for p in doc.paragraphs if p.text.strip().startswith(prefix)]
    if len(hits) != 1:
        raise ValueError(f"段落定位失败: {prefix!r}, hits={len(hits)}")
    return hits[0]


def replace_text(paragraph: Paragraph, text: str) -> None:
    """替换文字而保留段落属性及首个文本运行的字符格式。"""
    run_props = None
    for run in paragraph.runs:
        if run._r.rPr is not None:
            run_props = deepcopy(run._r.rPr)
            break
    ppr = paragraph._p.pPr
    for child in list(paragraph._p):
        if child is not ppr:
            paragraph._p.remove(child)
    run = paragraph.add_run(text)
    if run_props is not None:
        run._r.insert(0, run_props)


def clear_numbering(paragraph: Paragraph) -> None:
    ppr = paragraph._p.get_or_add_pPr()
    numpr = ppr.find(qn("w:numPr"))
    if numpr is not None:
        ppr.remove(numpr)


def _new_paragraph_from(template: Paragraph, text: str, style_name: str | None = None) -> Paragraph:
    new_p = OxmlElement("w:p")
    if template._p.pPr is not None:
        new_p.append(deepcopy(template._p.pPr))
    para = Paragraph(new_p, template._parent)
    if style_name is not None:
        para.style = style_name
    run = para.add_run(text)
    for old_run in template.runs:
        if old_run._r.rPr is not None:
            run._r.insert(0, deepcopy(old_run._r.rPr))
            break
    return para


def insert_after(anchor: Paragraph, text: str, template: Paragraph | None = None,
                 style_name: str | None = None) -> Paragraph:
    para = _new_paragraph_from(template or anchor, text, style_name)
    anchor._p.addnext(para._p)
    return para


def insert_before(anchor: Paragraph, text: str, template: Paragraph | None = None,
                  style_name: str | None = None) -> Paragraph:
    para = _new_paragraph_from(template or anchor, text, style_name)
    anchor._p.addprevious(para._p)
    return para


def replace_related_image(doc: Document, paragraph: Paragraph, image_path: Path) -> None:
    rel_ids = paragraph._p.xpath(".//a:blip/@r:embed")
    if len(rel_ids) != 1:
        raise ValueError(f"图片关系定位失败: {paragraph.text!r}, rels={rel_ids}")
    doc.part.related_parts[rel_ids[0]]._blob = image_path.read_bytes()


def find_image_paragraph(doc: Document, target_ref: str) -> Paragraph:
    for paragraph in doc.paragraphs:
        for rel_id in paragraph._p.xpath(".//a:blip/@r:embed"):
            if doc.part.rels[rel_id].target_ref == target_ref:
                return paragraph
    raise ValueError(f"找不到图片: {target_ref}")


